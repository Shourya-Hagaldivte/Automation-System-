"""Compatibility helpers for requirement-driven tender pricing endpoints."""

from __future__ import annotations

from datetime import datetime
from typing import Any

from services.procurement_intelligence import generate_tender_recommendations


def _currency(value: Any) -> str:
    try:
        number = float(str(value).replace(',', ''))
    except (TypeError, ValueError):
        number = 0.0
    return f"INR {number:,.2f}"


def build_tender_matches(requirements: dict[str, Any]) -> dict[str, Any]:
    """Return ranked supplier/company tender recommendations."""
    return generate_tender_recommendations({"requirements": requirements})


def rfp_document_lines(payload: dict[str, Any]) -> list[str]:
    """Create a text outline for the simple PDF fallback endpoint."""
    requirements = payload.get("requirements") or {}
    analysis = payload.get("tenderAnalysis") or payload.get("analysis") or {}
    if not analysis.get("tenders"):
        analysis = generate_tender_recommendations({"requirements": requirements})

    lines = [
        "REQUEST FOR PROPOSAL (RFP)",
        f"Generated: {datetime.now().strftime('%d %B %Y, %I:%M %p')}",
        "",
        "1. PROJECT DETAILS",
        f"Project Title: {requirements.get('title') or 'Procurement Requirement'}",
        f"Organization: {requirements.get('organization') or 'Not specified'}",
        f"Industry: {requirements.get('industry') or 'Not specified'}",
        f"Budget: {_currency(requirements.get('budget'))}",
        f"Timeline: {requirements.get('timeline') or 'Not specified'}",
        "",
        "2. REQUIRED ITEMS",
    ]

    for index, item in enumerate(requirements.get("items") or [], start=1):
        lines.append(f"{index}. {item.get('name')} - {item.get('quantity')} {item.get('unit')}")

    lines.extend(["", "3. TOP COMPANY TENDER COMPARISON"])
    for tender in analysis.get("tenders") or []:
        summary = tender.get("summary") or {}
        lines.append(
            f"Rank {tender.get('rank')}: {tender.get('company')} | "
            f"Match {tender.get('matchScore')}% | Lead time {tender.get('leadTime')} | "
            f"Grand Total {_currency(summary.get('grandTotal'))}"
        )

    lines.extend([
        "",
        "4. COMMERCIAL TERMS",
        "- Vendor must include product datasheets, compliance documents, GST details, warranty terms, and delivery schedule.",
        "- Prices should include material, freight, testing, insurance, applicable taxes, and all delivery charges.",
        "- Final purchase order rates should be validated against official vendor quotations before award.",
        "",
        "5. PRICING SOURCE NOTE",
        analysis.get("priceDisclaimer") or "Pricing generated by the procurement recommendation engine.",
    ])
    return lines
